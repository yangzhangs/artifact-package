PATH_SUFFIXES = ['_.github', '_github', '_root', '_docs']


def repo_of_filename(fname):
    """Map a downloaded filename ({owner}_{repo}[{path}]_contributing.md) to owner/repo."""
    base = fname[:-len('_contributing.md')]
    for suf in PATH_SUFFIXES:
        if base.endswith(suf):
            base = base[:-len(suf)]
            break
    if '_' not in base:
        return base
    owner, repo = base.split('_', 1)
    return f'{owner}/{repo}'


def repo_of_path(path, dl_dir):
    """Derive owner/repo from either a flat corpus or a per-repository directory tree."""
    rel = os.path.relpath(path, dl_dir)
    parts = rel.split(os.sep)
    fname = parts[-1]
    if len(parts) >= 2:
        parent = parts[-2]
        if '__' in parent:
            owner, repo = parent.split('__', 1)
            return f'{owner}/{repo}'
    if fname.endswith('_contributing.md'):
        return repo_of_filename(fname)
    if len(parts) >= 2 and '_' in parts[-2]:
        owner, repo = parts[-2].split('_', 1)
        return f'{owner}/{repo}'
    return None


def scan_files(dl_dir):
    files = []
    for root, _, names in os.walk(dl_dir):
        for name in names:
            if name.lower().endswith('contributing.md'):
                files.append(os.path.join(root, name))
    files.sort()
    if not files:
        raise SystemExit(
            f'No guideline files found under {dl_dir}. '
            'Files must end with CONTRIBUTING.md; accepted layouts are a flat corpus named '
            '{owner}_{repo}[{path}]_contributing.md or one directory per repository '
            'named {owner}__{repo}.')
    repo_l1 = defaultdict(set)   # repo -> set of matched L1 labels
    repo_l2 = defaultdict(set)   # repo -> set of matched L2 labels
    file_l1 = file_l2 = 0

    skipped = 0
    for fpath in files:
        with open(fpath, 'r', encoding='utf-8', errors='ignore') as f:
            content = f.read()
        content_lower = content.lower()
        repo = repo_of_path(fpath, dl_dir)
        if repo is None:
            skipped += 1
            continue

        hit1 = hit2 = False
        for pat, label in L1_PATTERNS:
            if re.search(pat, content_lower):
                repo_l1[repo].add(label)
                hit1 = True
        for pat, label in L2_PATTERNS:
            if re.search(pat, content_lower):
                repo_l2[repo].add(label)
                hit2 = True
        if hit1:
            file_l1 += 1
        if hit2:
            file_l2 += 1

    # A repository is a candidate when any of its guideline files matches
    # at least one pattern from either layer.
    candidates = {repo for repo in set(repo_l1) | set(repo_l2)}
    total_repos = len({repo_of_path(f, dl_dir) for f in files if repo_of_path(f, dl_dir)})
    return files, file_l1, file_l2, repo_l1, repo_l2, candidates, total_repos, skipped


def print_stats(files, file_l1, file_l2, repo_l1, repo_l2, candidates, total_repos, skipped=0):
    print("=== AIP Two-Layer Keyword Screening Results ===")
    print(f"Total files scanned: {len(files)}")
    print(f"Repositories with guideline files: {total_repos}")
    print(f"L1 hits (files): {file_l1}")
    print(f"L2 hits (files): {file_l2}")
    print(f"Candidate repositories (L1 or L2): {len(candidates)}")
    if skipped:
        print(f"Files skipped for unknown repository name: {skipped}")


def export_candidates(candidates, output_path):
    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['repo_name'])
        for repo in sorted(candidates):
            writer.writerow([repo])
    print(f"Exported candidate repositories: {output_path} ({len(candidates)} records)")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='AIP two-layer keyword screening')
    parser.add_argument('--dl-dir', required=True, help='Directory containing downloaded CONTRIBUTING.md files')
    parser.add_argument('--export', action='store_true', help='Export the candidate repository list as CSV')
    parser.add_argument('--output', default='screening_results.csv', help='Output CSV path')
    args = parser.parse_args()

    files, file_l1, file_l2, repo_l1, repo_l2, candidates, total_repos, skipped = scan_files(args.dl_dir)
    print_stats(files, file_l1, file_l2, repo_l1, repo_l2, candidates, total_repos, skipped)
    if args.export:
        export_candidates(candidates, args.output)
